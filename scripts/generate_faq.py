#!/usr/bin/env python3
"""Generate the FAQ from docs/faq/faq.json.

Writes two outputs from the same source:

  docs/faq.md          Markdown FAQ, grouped by topic
  docs/faq/index.html  Searchable FAQ page with "was this helpful?" votes

The source is validated first. Every topic and question ID must be unique, every
question must name a known topic, and every link must point to a file that
exists in the repository. Validation errors fail the run, and so does CI.

Standard library only. Usage:

  python3 scripts/generate_faq.py          # regenerate the files
  python3 scripts/generate_faq.py --check  # exit 1 if the files are stale or invalid (CI)
"""

import argparse
import json
import os
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SOURCE = REPO_ROOT / "docs" / "faq" / "faq.json"
MARKDOWN_OUT = REPO_ROOT / "docs" / "faq.md"
HTML_OUT = REPO_ROOT / "docs" / "faq" / "index.html"
ID_PATTERN = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
GENERATED_NOTE = "Generated by scripts/generate_faq.py from docs/faq/faq.json. Do not edit by hand."


def load_source():
    data = json.loads(SOURCE.read_text())
    errors = []

    topic_ids = set()
    for topic in data["topics"]:
        if not ID_PATTERN.match(topic["id"]):
            errors.append(f"topic id `{topic['id']}` must be lowercase kebab-case")
        if topic["id"] in topic_ids:
            errors.append(f"duplicate topic id `{topic['id']}`")
        topic_ids.add(topic["id"])

    question_ids = set()
    for question in data["questions"]:
        qid = question["id"]
        if not ID_PATTERN.match(qid):
            errors.append(f"question id `{qid}` must be lowercase kebab-case")
        if qid in question_ids:
            errors.append(f"duplicate question id `{qid}`")
        question_ids.add(qid)
        if question["topic"] not in topic_ids:
            errors.append(f"question `{qid}` names unknown topic `{question['topic']}`")
        if not question.get("answer") or not all(isinstance(p, str) and p.strip() for p in question["answer"]):
            errors.append(f"question `{qid}` needs at least one non-empty answer paragraph")
        for link in question.get("links", []):
            if not (REPO_ROOT / link["path"]).exists():
                errors.append(f"question `{qid}` links to missing file `{link['path']}`")

    if errors:
        for error in errors:
            print(f"generate_faq: error: {error}", file=sys.stderr)
        raise SystemExit(1)
    return data


def relative_href(repo_path, from_dir):
    """Return a link from from_dir to a repo-relative path, in forward-slash form."""
    return Path(os.path.relpath(REPO_ROOT / repo_path, from_dir)).as_posix()


def render_markdown(data):
    topics = {t["id"]: t["title"] for t in data["topics"]}
    lines = [
        "# Frequently Asked Questions",
        "",
        f"<!-- {GENERATED_NOTE} -->",
        "",
        "Answers to common questions about Mainstay. Browse by topic below, or use the",
        "[searchable FAQ page](faq/index.html).",
        "",
        "## Topics",
        "",
    ]
    for topic in data["topics"]:
        lines.append(f"- [{topic['title']}](#{topic['id']})")
    lines.append("")

    for topic in data["topics"]:
        questions = [q for q in data["questions"] if q["topic"] == topic["id"]]
        if not questions:
            continue
        lines += [f"## {topics[topic['id']]}", ""]
        for question in questions:
            lines += [f"### {question['question']}", ""]
            for paragraph in question["answer"]:
                lines += [paragraph, ""]
            if question.get("links"):
                see_also = ", ".join(
                    f"[{link['title']}]({relative_href(link['path'], MARKDOWN_OUT.parent)})"
                    for link in question["links"]
                )
                lines += [f"**See also:** {see_also}", ""]
    return "\n".join(lines).rstrip() + "\n"


