def render_html(data):
    html_dir = HTML_OUT.parent
    topics = [{"id": t["id"], "title": t["title"]} for t in data["topics"]]
    questions = []
    for question in data["questions"]:
        questions.append(
            {
                "id": question["id"],
                "topic": question["topic"],
                "question": question["question"],
                "answer": question["answer"],
                "tags": question.get("tags", []),
                "links": [
                    {"title": link["title"], "href": relative_href(link["path"], html_dir)}
                    for link in question.get("links", [])
                ],
            }
        )
    payload = json.dumps({"topics": topics, "questions": questions}, indent=1, ensure_ascii=False)
    # Keep the JSON from closing its <script> element early.
    payload = payload.replace("</", "<\\/")
    return HTML_TEMPLATE.replace("__GENERATED_NOTE__", GENERATED_NOTE).replace("__DATA__", payload)


def render_outputs():
    data = load_source()
    return {MARKDOWN_OUT: render_markdown(data), HTML_OUT: render_html(data)}


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if committed outputs are out of date")
    args = parser.parse_args(argv)

    stale = []
    for target, content in render_outputs().items():
        if args.check:
            if not target.exists() or target.read_text() != content:
                stale.append(str(target.relative_to(REPO_ROOT)))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
            print(f"wrote {target.relative_to(REPO_ROOT)}")

    if stale:
        print("FAQ outputs are out of date. Run: python3 scripts/generate_faq.py")
        for path in stale:
            print(f"  stale: {path}")
        return 1
    if args.check:
        print("FAQ outputs are up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
